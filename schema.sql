-- ---------- الجداول ----------
create table if not exists public.companies (
  id          bigint generated always as identity primary key,
  code        text   not null,
  name        text   not null,
  active      boolean not null default true,
  expires     date,
  max_users   int    not null default 0,
  max_cands   int    not null default 0,
  created_at  timestamptz not null default now()
);
create unique index if not exists companies_code_uq on public.companies (upper(code));

create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  cid         bigint references public.companies(id) on delete cascade,   -- null = المدير الرئيسي
  role        text   not null check (role in ('super','cadmin','user')),
  username    text   not null,
  name        text,
  active      boolean not null default true,
  perms       jsonb  not null default '{}'::jsonb,                          -- { "jobId": 1|2|3 }
  created_at  timestamptz not null default now(),
  constraint profiles_scope_ck check ((role='super' and cid is null) or (role<>'super' and cid is not null))
);
create unique index if not exists profiles_company_username_uq on public.profiles (cid, lower(username)) where cid is not null;
create index if not exists profiles_cid_idx on public.profiles (cid);

create table if not exists public.company_settings (
  cid   bigint primary key references public.companies(id) on delete cascade,
  data  jsonb not null default '{}'::jsonb
);

create table if not exists public.jobs (
  id         bigint generated by default as identity primary key,
  cid        bigint not null references public.companies(id) on delete cascade,
  data       jsonb  not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create index if not exists jobs_cid_idx on public.jobs (cid);

create table if not exists public.cands (
  id         bigint generated by default as identity primary key,
  cid        bigint not null references public.companies(id) on delete cascade,
  job_id     bigint not null references public.jobs(id) on delete cascade,
  data       jsonb  not null default '{}'::jsonb,                           -- بدون النص الكامل للسيرة
  updated_at timestamptz not null default now()
);
create index if not exists cands_cid_idx on public.cands (cid);
create index if not exists cands_job_idx on public.cands (job_id);

create table if not exists public.cand_texts (                              -- النص الكامل للسيرة (بيتحمّل عند الحاجة)
  id    bigint primary key references public.cands(id) on delete cascade,
  cid   bigint not null,
  text  text   not null
);
create index if not exists cand_texts_cid_idx on public.cand_texts (cid);

create table if not exists public.audit (
  id        bigint generated always as identity primary key,
  cid       bigint references public.companies(id) on delete cascade,
  ts        timestamptz not null default now(),
  username  text,
  role      text,
  action    text,
  detail    text
);
create index if not exists audit_cid_ts_idx on public.audit (cid, ts desc);

-- ---------- دوال مساعدة (security definer علشان تتفادى التكرار اللانهائي في RLS) ----------
create or replace function public.app_role() returns text
language sql stable security definer set search_path = public as $$
  select p.role from public.profiles p
  where p.id = auth.uid() and p.active
    and (p.role = 'super' or exists (
          select 1 from public.companies c
          where c.id = p.cid and c.active and (c.expires is null or c.expires >= current_date)));
$$;

create or replace function public.app_cid() returns bigint
language sql stable security definer set search_path = public as $$
  select p.cid from public.profiles p
  where p.id = auth.uid() and p.active
    and (p.role = 'super' or exists (
          select 1 from public.companies c
          where c.id = p.cid and c.active and (c.expires is null or c.expires >= current_date)));
$$;

create or replace function public.company_ok(p_cid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select case when public.app_role() = 'super' then true
              else p_cid is not null and p_cid = public.app_cid() end;
$$;

-- مستوى الصلاحية على وظيفة: 0 لا شيء / 1 عرض / 2 عرض وتعديل / 3 مسؤول الوظيفة
create or replace function public.job_level(p_job bigint) returns int
language plpgsql stable security definer set search_path = public as $$
declare me record; jc bigint;
begin
  select p.role, p.cid, p.perms into me from public.profiles p where p.id = auth.uid() and p.active;
  if not found then return 0; end if;
  if me.role = 'super' then return 3; end if;
  select cid into jc from public.jobs where id = p_job;
  if jc is null or jc <> me.cid then return 0; end if;
  if not exists (select 1 from public.companies c where c.id = me.cid and c.active and (c.expires is null or c.expires >= current_date)) then return 0; end if;
  if me.role = 'cadmin' then return 3; end if;
  return coalesce((me.perms ->> (p_job::text))::int, 0);
end $$;

create or replace function public.cand_level(p_cand bigint) returns int
language plpgsql stable security definer set search_path = public as $$
declare jid bigint;
begin
  select job_id into jid from public.cands where id = p_cand;
  if jid is null then return 0; end if;
  return public.job_level(jid);
end $$;

-- مستوى الصلاحية على ملف في التخزين: الاسم بالشكل  <cid>/<candId>  أو  <cid>/app<candId>
create or replace function public.file_level(p_name text) returns int
language plpgsql stable security definer set search_path = public as $$
declare c bigint; k bigint; jid bigint; cc bigint;
begin
  c := split_part(p_name, '/', 1)::bigint;
  k := regexp_replace(split_part(p_name, '/', 2), '^app', '')::bigint;
  select job_id, cid into jid, cc from public.cands where id = k;
  if jid is null or cc <> c then return 0; end if;
  return public.job_level(jid);
exception when others then
  return 0;
end $$;

-- تحويل كود الشركة لرقمها (متاح قبل تسجيل الدخول)
create or replace function public.company_id_by_code(p_code text) returns bigint
language sql stable security definer set search_path = public as $$
  select id from public.companies
  where upper(regexp_replace(code, '[^A-Za-z0-9]', '', 'g')) = upper(regexp_replace(coalesce(p_code,''), '[^A-Za-z0-9]', '', 'g'))
  limit 1;
$$;

-- حالة الحساب الحالي بعد الدخول (بتشتغل حتى لو الشركة موقوفة، علشان نعرض رسالة مناسبة)
create or replace function public.my_status() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce((
    select jsonb_build_object(
      'id', p.id, 'role', p.role, 'cid', p.cid, 'username', p.username, 'name', p.name, 'perms', p.perms,
      'active', p.active,
      'company_state', case when p.role = 'super' then 'ok'
                            when c.id is null then 'missing'
                            when not c.active then 'suspended'
                            when c.expires is not null and c.expires < current_date then 'expired'
                            else 'ok' end)
    from public.profiles p left join public.companies c on c.id = p.cid
    where p.id = auth.uid()), 'null'::jsonb);
$$;

-- حد السير لكل شركة (على مستوى القاعدة نفسها)
create or replace function public.enforce_cand_limit() returns trigger
language plpgsql security definer set search_path = public as $$
declare m int; n bigint;
begin
  if new.id is not null and exists (select 1 from public.cands where id = new.id) then return new; end if;   -- upsert لسجل موجود
  select max_cands into m from public.companies where id = new.cid;
  if coalesce(m, 0) > 0 then
    select count(*) into n from public.cands where cid = new.cid;
    if n >= m then raise exception 'company_cand_limit'; end if;
  end if;
  return new;
end $$;
drop trigger if exists cands_limit_trg on public.cands;
create trigger cands_limit_trg before insert on public.cands for each row execute function public.enforce_cand_limit();

