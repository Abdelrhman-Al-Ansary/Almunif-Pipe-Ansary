-- ---------- السياسات ----------
-- companies
drop policy if exists companies_select on public.companies;
create policy companies_select on public.companies for select to authenticated
  using ((select public.app_role()) = 'super' or id = (select public.app_cid()));
drop policy if exists companies_update on public.companies;
create policy companies_update on public.companies for update to authenticated
  using ((select public.app_role()) = 'super') with check ((select public.app_role()) = 'super');

-- profiles
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated
  using ( id = auth.uid()
       or (select public.app_role()) = 'super'
       or ((select public.app_role()) = 'cadmin' and cid = (select public.app_cid())) );
drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles for update to authenticated
  using ( (select public.app_role()) = 'super'
       or ((select public.app_role()) = 'cadmin' and cid = (select public.app_cid()) and role = 'user') )
  with check ( (select public.app_role()) = 'super'
       or ((select public.app_role()) = 'cadmin' and cid = (select public.app_cid()) and role = 'user') );

-- company_settings
drop policy if exists cs_select on public.company_settings;
create policy cs_select on public.company_settings for select to authenticated using (public.company_ok(cid));
drop policy if exists cs_insert on public.company_settings;
create policy cs_insert on public.company_settings for insert to authenticated
  with check ((select public.app_role()) in ('super','cadmin') and public.company_ok(cid));
drop policy if exists cs_update on public.company_settings;
create policy cs_update on public.company_settings for update to authenticated
  using ((select public.app_role()) in ('super','cadmin') and public.company_ok(cid))
  with check ((select public.app_role()) in ('super','cadmin') and public.company_ok(cid));

-- jobs
drop policy if exists jobs_select on public.jobs;
create policy jobs_select on public.jobs for select to authenticated
  using ( (select public.app_role()) = 'super'
       or ((select public.app_role()) = 'cadmin' and cid = (select public.app_cid()))
       or public.job_level(id) >= 1 );
drop policy if exists jobs_insert on public.jobs;
create policy jobs_insert on public.jobs for insert to authenticated
  with check ((select public.app_role()) in ('super','cadmin') and public.company_ok(cid));
drop policy if exists jobs_update on public.jobs;
create policy jobs_update on public.jobs for update to authenticated
  using (public.job_level(id) >= 3)
  with check (public.job_level(id) >= 3 and public.company_ok(cid));
drop policy if exists jobs_delete on public.jobs;
create policy jobs_delete on public.jobs for delete to authenticated
  using ((select public.app_role()) in ('super','cadmin') and public.company_ok(cid));

-- cands
drop policy if exists cands_select on public.cands;
create policy cands_select on public.cands for select to authenticated
  using ( (select public.app_role()) = 'super'
       or ((select public.app_role()) = 'cadmin' and cid = (select public.app_cid()))
       or public.job_level(job_id) >= 1 );
drop policy if exists cands_insert on public.cands;
create policy cands_insert on public.cands for insert to authenticated
  with check ( public.job_level(job_id) >= 2 and cid = (select j.cid from public.jobs j where j.id = job_id) );
drop policy if exists cands_update on public.cands;
create policy cands_update on public.cands for update to authenticated
  using (public.job_level(job_id) >= 2)
  with check ( public.job_level(job_id) >= 2 and cid = (select j.cid from public.jobs j where j.id = job_id) );
drop policy if exists cands_delete on public.cands;
create policy cands_delete on public.cands for delete to authenticated using (public.job_level(job_id) >= 2);

-- cand_texts
drop policy if exists ct_select on public.cand_texts;
create policy ct_select on public.cand_texts for select to authenticated using (public.cand_level(id) >= 1);
drop policy if exists ct_insert on public.cand_texts;
create policy ct_insert on public.cand_texts for insert to authenticated
  with check (public.cand_level(id) >= 2 and cid = (select c.cid from public.cands c where c.id = cand_texts.id));
drop policy if exists ct_update on public.cand_texts;
create policy ct_update on public.cand_texts for update to authenticated
  using (public.cand_level(id) >= 2) with check (public.cand_level(id) >= 2);
drop policy if exists ct_delete on public.cand_texts;
create policy ct_delete on public.cand_texts for delete to authenticated using (public.cand_level(id) >= 2);

-- audit
drop policy if exists audit_select on public.audit;
create policy audit_select on public.audit for select to authenticated
  using ( (select public.app_role()) = 'super'
       or ((select public.app_role()) = 'cadmin' and cid = (select public.app_cid())) );
drop policy if exists audit_insert on public.audit;
create policy audit_insert on public.audit for insert to authenticated
  with check ( (select public.app_role()) is not null
           and ((select public.app_role()) = 'super' or cid = (select public.app_cid())) );
drop policy if exists audit_delete on public.audit;
create policy audit_delete on public.audit for delete to authenticated using ((select public.app_role()) = 'super');

